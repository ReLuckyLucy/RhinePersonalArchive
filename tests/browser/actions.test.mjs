import assert from 'node:assert/strict';
import {saveDossier} from '../../server/archive/repository.ts';
import {importFiles} from '../../server/sources/import.ts';
import {getSource,updateSource} from '../../server/sources/repository.ts';
const unknown={value:null,precision:'unknown'};
const input={kind:'project',title:'操作入口合成项目',aliases:[],dateRange:{start:unknown,end:unknown,ongoing:false},organization:'',role:'',summary:'',skills:[],typedDetails:{},favorite:false};
export async function run({page,baseURL,ctx}){
 const dossier=saveDossier(ctx,input,null),other=saveDossier(ctx,{...input,title:'第二个合成项目'},null);
 const report=await importFiles(ctx,[{name:'failed.txt',stream:[Buffer.from('synthetic failed material')]}],dossier.id);
 updateSource(ctx,{...getSource(ctx,report.sourceIds[0]),extractionState:'failed'});
 await page.addInitScript(()=>{sessionStorage.setItem('rhine:entered','1');localStorage.setItem('rhine:last-page','review');});
 await page.goto(baseURL);
 const row=page.locator(`[data-review-id="${dossier.id}"]`);
 await row.getByRole('button',{name:'补充角色',exact:true}).click({timeout:5000});
 await page.waitForFunction(()=>document.activeElement?.getAttribute('name')==='role');
 await page.getByLabel('个人角色',{exact:true}).fill('本人开发');
 await page.getByRole('button',{name:'保存档案',exact:true}).click();await page.getByText('已保存',{exact:true}).waitFor();
 await page.getByRole('button',{name:'返回待整理',exact:true}).click();
 await page.waitForFunction(id=>document.activeElement?.closest('[data-review-id]')?.getAttribute('data-review-id')===id,dossier.id,{timeout:1500});
 assert.equal(await row.getByRole('button',{name:'补充角色',exact:true}).count(),0);
 await row.getByRole('button',{name:'补充日期',exact:true}).click();
 await page.waitForFunction(()=>document.activeElement?.getAttribute('name')==='startPrecision');
 await page.getByRole('button',{name:'返回待整理',exact:true}).click();
 await row.getByRole('button',{name:'核对贡献',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('[data-tab=facts]')?.getAttribute('aria-current')==='true');
 await page.getByRole('button',{name:'返回待整理',exact:true}).click();
 await row.getByRole('button',{name:'处理材料',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('[data-tab=sources]')?.getAttribute('aria-current')==='true');
 await page.getByRole('button',{name:'返回待整理',exact:true}).click();
 await page.getByRole('button',{name:'个人档案',exact:true}).click();
 const add=page.getByRole('button',{name:'添加材料',exact:true});await add.click();
 const dialog=page.getByRole('dialog',{name:'添加材料',exact:true});
 await dialog.getByLabel('归属档案',{exact:true}).selectOption(other.id);
 await dialog.getByLabel('选择材料文件',{exact:true}).setInputFiles({name:'new-proof.txt',mimeType:'text/plain',buffer:Buffer.from('added from the homepage')});
 await page.route('**/api/sources/upload?*',route=>route.fulfill({status:500,json:{ok:false,error:{message:'合成上传故障'}}}));
 await dialog.getByRole('button',{name:'添加到档案',exact:true}).click();await dialog.getByText('添加失败：合成上传故障',{exact:true}).waitFor();
 assert.equal(await dialog.getByLabel('归属档案',{exact:true}).inputValue(),other.id);
 assert.equal(await dialog.getByLabel('选择材料文件',{exact:true}).evaluate(el=>el.files.length),1,'failed upload preserves chosen file');
 await page.unroute('**/api/sources/upload?*');
 await dialog.getByRole('button',{name:'添加到档案',exact:true}).click();await dialog.waitFor({state:'detached'});
 await page.waitForFunction(()=>document.querySelector('[data-tab=sources]')?.getAttribute('aria-current')==='true');
 await page.locator('[data-source]').filter({hasText:'new-proof.txt'}).waitFor();
 assert.equal(ctx.db.prepare('SELECT count(*) n FROM dossiers').get().n,2,'global upload must not create a placeholder dossier');
 assert.equal(ctx.db.prepare('SELECT count(*) n FROM dossier_sources WHERE dossier_id=?').get(other.id).n,1);
 assert.equal(ctx.db.prepare('SELECT count(*) n FROM jobs').get().n,0,'adding a file must not start extraction');
 await page.getByRole('button',{name:'返回档案目录',exact:true}).click();
 await page.getByText('更多操作',{exact:true}).click();
 await page.getByRole('button',{name:'导入清单',exact:true}).click();await page.getByRole('dialog',{name:'导入已有资料',exact:true}).waitFor();
 await page.keyboard.press('Escape');await page.getByRole('dialog').waitFor({state:'detached'});
 await page.keyboard.press('Escape');assert.equal(await page.locator('.archive-more').evaluate(el=>el.open),false,'Escape closes advanced actions');
 for(const width of [1440,760,390,334]){await page.setViewportSize({width,height:900});assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);assert.equal(await add.isVisible(),true);await page.screenshot({path:`verification/private/screenshots/actions-${width}.png`});}
}
