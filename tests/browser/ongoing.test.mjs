import assert from 'node:assert/strict';
import {seedConfirmed} from '../helpers/seed.ts';
import {saveDossier,getDossier} from '../../server/archive/repository.ts';
import {getFact,getFactHistory} from '../../server/archive/facts.ts';

export async function run({page,baseURL,ctx}){
  const {fact,dossier}=await seedConfirmed(ctx);
  const {revision,archivedAt,visitedAt,...input}=dossier;
  saveDossier(ctx,{...input,dateRange:{...dossier.dateRange,ongoing:true}},revision);
  await page.addInitScript(()=>sessionStorage.setItem('rhine:entered','1'));
  const openFacts=async()=>{
    await page.goto(baseURL);
    await page.getByRole('button',{name:'个人档案',exact:true}).click();
    await page.locator(`[data-dossier="${dossier.id}"]`).click();
    await page.locator('[data-read]').click();
    await page.getByRole('button',{name:'个人贡献',exact:true}).click();
  };
  await openFacts();
  await page.locator(`[data-edit-fact="${fact.id}"]`).click();
  let dialog=page.getByRole('dialog',{name:'编辑个人事实',exact:true});
  const ongoing=dialog.locator('[data-field="dateRange.ongoing"]');
  assert.equal(await ongoing.count(),1,'ongoing status must be available for explicit evidence selection');
  assert.equal(await ongoing.isChecked(),false,'a legacy fact must not inherit the dossier ongoing selection');
  let state=dialog.getByLabel('仍在进行',{exact:true});
  assert.equal(await state.count(),1,'ongoing status must allow an explicit yes/no correction');
  assert.equal(await state.inputValue(),'true');
  assert.equal(await state.locator('option:checked').innerText(),'是，仍在进行');
  await state.selectOption('false');
  assert.equal(await ongoing.isChecked(),false,'changing the state must not select its proof field');
  await state.selectOption('true');
  assert.equal(await ongoing.isChecked(),false);
  await ongoing.check();
  await dialog.getByRole('button',{name:'保存事实',exact:true}).click();
  await dialog.waitFor({state:'detached'});
  let revised=getFact(ctx,fact.id);
  assert.equal(revised.fieldValues['dateRange.ongoing'],true);
  assert.equal(revised.status,'review');
  await page.locator(`[data-confirm="${fact.id}"]`).click();
  await page.locator(`[data-fact-id="${fact.id}"]`).getByText('已确认',{exact:true}).waitFor();
  assert.equal(getFact(ctx,fact.id).status,'confirmed');

  // Revising a confirmed snapshot must not silently replace it with newer dossier values.
  const beforeCorrection=getFactHistory(ctx,fact.id);
  const current=getDossier(ctx,dossier.id),{revision:currentRevision,archivedAt:at,visitedAt:visited,...currentInput}=current;
  saveDossier(ctx,{...currentInput,role:'合成修订角色',dateRange:{start:{value:'2025',precision:'year'},end:{value:null,precision:'unknown'},ongoing:false}},currentRevision);
  await openFacts();
  await page.locator(`[data-edit-fact="${fact.id}"]`).click();
  dialog=page.getByRole('dialog',{name:'编辑个人事实',exact:true});
  assert.equal(await dialog.locator('[data-field="dateRange.ongoing"]').isChecked(),true);
  state=dialog.getByLabel('仍在进行',{exact:true});
  assert.equal(await state.inputValue(),'true');
  assert.match(await dialog.locator('[data-field="dateRange.start"]').locator('..').innerText(),/2024/);
  assert.match(await dialog.locator('[data-field="role"]').locator('..').innerText(),/开发/);
  const adoptRole=dialog.getByRole('button',{name:'采用档案当前值：个人角色',exact:true});
  const adoptStart=dialog.getByRole('button',{name:'采用档案当前值：开始时间',exact:true});
  assert.equal(await adoptRole.count(),1,'a corrected live role must remain explicitly adoptable');
  assert.equal(await adoptStart.count(),1,'a corrected live start date must remain explicitly adoptable');
  const roleProof=dialog.locator('[data-field="role"]');
  await roleProof.uncheck();
  await adoptRole.click();
  assert.equal(await roleProof.isChecked(),false,'adopting a value must not select its proof field');
  assert.match(await roleProof.locator('..').innerText(),/合成修订角色/);
  await roleProof.check();
  await adoptStart.click();
  assert.match(await dialog.locator('[data-field="dateRange.start"]').locator('..').innerText(),/2025/);
  await state.selectOption('false');
  await dialog.getByRole('button',{name:'保存事实',exact:true}).click();
  await dialog.waitFor({state:'detached'});
  revised=getFact(ctx,fact.id);
  assert.equal(revised.fieldValues['dateRange.ongoing'],false);
  assert.equal(revised.fieldValues.role,'合成修订角色');
  assert.deepEqual(revised.fieldValues['dateRange.start'],{value:'2025',precision:'year'});
  assert.equal(revised.status,'review','correcting ongoing status must revoke the previous confirmation');
  assert.equal(revised.confirmedAt,null);
  assert.deepEqual(getFactHistory(ctx,fact.id).slice(0,beforeCorrection.length),beforeCorrection,'adopting current values must preserve every historical revision');
  await page.locator(`[data-confirm="${fact.id}"]`).click();
  await page.locator(`[data-fact-id="${fact.id}"]`).getByText('已确认',{exact:true}).waitFor();
  assert.equal(getFact(ctx,fact.id).status,'confirmed');
  assert.equal(getFact(ctx,fact.id).fieldValues['dateRange.ongoing'],false);
  await page.getByRole('button',{name:'新增贡献或成果',exact:true}).click();
  dialog=page.getByRole('dialog',{name:'编辑个人事实',exact:true});
  assert.equal(await dialog.locator('[data-field="dateRange.ongoing"]').isChecked(),false);
  state=dialog.getByLabel('仍在进行',{exact:true});
  assert.equal(await state.inputValue(),'false');
  assert.equal(await state.locator('option:checked').innerText(),'否，非进行中');
  await page.keyboard.press('Escape');
  await dialog.waitFor({state:'detached'});
}
